use proptest::prelude::*;

use super::*;

const MAX_PROP_BYTES: usize = 64;
const MAX_PROP_VECTOR: usize = 64;
const MAX_PROP_MODULES: u32 = 32;
const MAX_PROP_BYTE: u16 = u8::MAX as u16;

proptest! {
    // r[verify scheme-logic.evidence.positive]
    // r[verify scheme-logic.interning]
    #[test]
    fn prop_new_intern_key_resolves_original(
        bytes in prop::collection::vec(any::<u8>(), 1..=MAX_PROP_BYTES),
    ) {
        let value = intern_value(InternKind::Symbol, &bytes);
        let result = intern(&empty_interner(), value.clone())
            .expect("bounded generated value should intern");
        prop_assert_eq!(resolve(&result.table, result.key), Ok(value));
    }

    // r[verify scheme-logic.evidence.positive]
    // r[verify scheme-logic.collections-bytevectors]
    #[test]
    fn prop_vector_update_preserves_length(
        raw in prop::collection::vec(any::<u16>(), 1..=MAX_PROP_VECTOR),
        replacement in any::<u32>(),
    ) {
        let values = raw
            .iter()
            .map(|value| NodeId(u32::from(*value)))
            .collect::<Vec<_>>();
        let index = u32::try_from(values.len() - 1)
            .expect("bounded generated vector index should fit");
        let updated = update_vector(&values, index, NodeId(replacement))
            .expect("last index should be admitted");
        prop_assert_eq!(updated.len(), values.len());
        prop_assert_eq!(updated[index as usize], NodeId(replacement));
    }

    // r[verify scheme-logic.evidence.positive]
    // r[verify scheme-logic.collections-bytevectors]
    #[test]
    fn prop_byte_domain_is_admitted(
        elements in prop::collection::vec(0u16..=MAX_PROP_BYTE, 0..=MAX_PROP_VECTOR),
    ) {
        let declared_length = u32::try_from(elements.len())
            .expect("bounded generated bytevector length should fit");
        let envelope = BytevectorEnvelope {
            declared_length,
            elements,
        };
        prop_assert_eq!(admit_bytevector(&envelope), Ok(()));
    }

    // r[verify scheme-logic.evidence.positive]
    // r[verify scheme-logic.module-graph]
    #[test]
    fn prop_linear_import_closure_visits_each_module_once(
        module_count in 1u32..=MAX_PROP_MODULES,
    ) {
        let modules = (0..module_count)
            .map(|id| ModuleRecord {
                id: ModuleId(id),
                exports: vec![NameId(PROVIDED_NAME)],
            })
            .collect::<Vec<_>>();
        let imports = (0..module_count.saturating_sub(1))
            .map(|id| ImportEdge {
                from: ModuleId(id),
                target: ModuleId(id + 1),
                name: NameId(PROVIDED_NAME),
            })
            .collect::<Vec<_>>();
        let graph = ModuleGraph { modules, imports };
        let closure = import_closure(&graph, ModuleId(MODULE_CLIENT), module_count)
            .expect("linear graph should fit exact budget");
        prop_assert_eq!(closure.consumed_budget, module_count);
        prop_assert_eq!(closure.modules.len(), module_count as usize);
    }
}
